import { readFile, writeFile } from 'node:fs/promises';
const assets = {};
for (const [path,file,type] of [['/manrope-latin.woff2','public/fonts/manrope-latin.woff2','font/woff2'],['/eyes-blue.png','public/icon-512.png','image/png'],['/geist-400.woff2','public/fonts/geist-400.woff2','font/woff2'],['/geist-600.woff2','public/fonts/geist-600.woff2','font/woff2']]) {
  assets[path] = {type,data:(await readFile(file)).toString('base64')};
}
await writeFile('worker/assets.js','// Generated by scripts/build-assets.mjs.\nexport const assets = '+JSON.stringify(assets)+';\n');
